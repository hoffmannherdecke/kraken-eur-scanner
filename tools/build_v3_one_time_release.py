"""Deterministic reviewed release variant of the ONE existing PR661 operator.

Never executes PowerShell, SQL, or a host operation. The dormant original is
unchanged. Exact edits replace fixture-only admission with the new signed
production boundary; native task/process/restore implementations are reused.
"""
from hashlib import sha256
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/minipc-v3-paper-cutover-operator-INACTIVE.ps1'
OUTPUT = ROOT / 'tools/v3-one-time-originalhost-release.psm1'
SOURCE_SHA = '3f1649306ef6ae6da13ee521849e36e47a8842de3f40f1f5af849f640ef892e7'


def build() -> str:
    raw = SOURCE.read_bytes()
    if sha256(raw).hexdigest() != SOURCE_SHA:
        raise ValueError('V3_RELEASE_ORIGINAL_OPERATOR_DRIFT')
    s = raw.decode('utf-8')
    s = s[s.index('function Test-V3Pr661SignedCloudBoundaryFields('):s.index('\nif($ExpectedPreparedFenceSha256 -and -not $ExecuteOriginalhostArmedOnly)')]
    def edit(old, new, count=1):
        nonlocal s
        if s.count(old) != count:
            raise ValueError('V3_RELEASE_REVIEWED_SEAM_DRIFT: ' + old[:90])
        s = s.replace(old, new)
    start = s.index('function Test-V3Pr661HostedOperatorScope(')
    end = s.index('function Invoke-V3Pr515ScopedNativeStopSOURCE_ONLY(', start)
    s = s[:start] + '''# Release admission replaces fixture admission, never the native implementation.
function Test-V3Pr661HostedOperatorScope([string]$Root,[string[]]$Tasks) {
 return (Test-V3ReleaseOriginalhostScope -Root $Root -Tasks $Tasks)
}
''' + s[end:]
    edit("   else{$false}\n  if(-not $scopeValid){\n   throw 'V3_ISSUER_BOUND_NATIVE_STOP_PRODUCTION_RELEASE_HOLD'",
         "   else{Test-V3ReleaseOriginalhostScope -Root $script:V3ReleaseRoot -Tasks $tasks}\n  if(-not $scopeValid){\n   throw 'V3_ISSUER_BOUND_NATIVE_STOP_PRODUCTION_RELEASE_HOLD'")
    edit("   else{$false}\n  if(-not $scopeValid){\n   throw 'V3_ISSUER_BOUND_NATIVE_RESTORE_PRODUCTION_RELEASE_HOLD'",
         "   else{Test-V3ReleaseOriginalhostScope -Root $script:V3ReleaseRoot -Tasks $TaskNames}\n  if(-not $scopeValid){\n   throw 'V3_ISSUER_BOUND_NATIVE_RESTORE_PRODUCTION_RELEASE_HOLD'")
    # Preserve prestop cryptographic verification, then require a separately
    # read terminal abort BEFORE the first native task mutation. The database
    # terminal barrier rejects all future intent/UNKNOWN appends to this epoch.
    edit(' # Exactly these two native task mutations, never Lifecycle or CloudSync.',
         " Assert-V3ReleaseMutationBoundary -Phase 'STOP'\n # Exactly these two native task mutations, never Lifecycle or CloudSync.")
    edit('  # Task definitions cannot be enabled while the held kernel handles exist.',
         "  Assert-V3ReleaseMutationBoundary -Phase 'RESTORE'\n  # Task definitions cannot be enabled while the held kernel handles exist.")
    edit(" $root=Join-Path ([IO.Path]::GetFullPath($IsolatedRoot).TrimEnd('\\')) 'State'",
         " Assert-V3ReleaseMutationBoundary -Phase 'ARCHIVE'\n $root=Join-Path ([IO.Path]::GetFullPath($IsolatedRoot).TrimEnd('\\')) 'State'")
    # PR661 computed this result but did not reject it before STOP. Release
    # admission must not let lease acquisition extend the 30-second freshness.
    edit(' foreach($name in $tasks){\n  Stop-ScheduledTask',
         " if($issuerAfterLease.signed_cloud_row_matches_pre_stop_inhibit -ne $true){throw 'V3_RELEASE_ISSUER_EXPIRED_AFTER_LEASE'}\n foreach($name in $tasks){\n  Stop-ScheduledTask")
    # Gate B is strictly AFTER terminal abort. Keep the original pre-abort
    # verifier callable for Gate A; only generated native call sites consume
    # the existing signed terminal Reader under the unchanged STOP freshness.
    edit('=Test-V3Pr661SignedIssuerPrestopReceipt',
         '=Test-V3ReleaseSignedTerminalPrestopReceipt', count=5)
    # Leave all other dormant phase-A/QUIESCED/source-only guards intact.
    prefix = '''# GENERATED by tools/build_v3_one_time_release.py; review the generator AND this file.
# Original PR661 native owner, separately gated RELEASE CANDIDATE / NOT APPROVED.
# No CAS, V3 writer start, new task, credential, or Paper rotation.
$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot 'v3-one-time-release-authorization.psm1') -Force
$script:V3ReleaseContext=$null
$script:V3ReleaseRoot=''
'''
    runtime = (ROOT / 'tools/v3-one-time-originalhost-boundary.ps1').read_text()
    return prefix + s + '\n' + runtime + '\nExport-ModuleMember -Function Invoke-V3OneTimeOriginalhostRelease\n'

if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    result = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit('V3_RELEASE_GENERATED_OPERATOR_STALE')
    else:
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')
